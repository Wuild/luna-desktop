import Meta from 'gi://Meta';
import St from 'gi://St';
import Shell from 'gi://Shell';
import Clutter from 'gi://Clutter';
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';
import * as Scripting from 'resource:///org/gnome/shell/ui/scripting.js';
function assert(value, message) { if (!value) throw new Error(message); }
export async function run() {
    await Scripting.sleep(1500);
    Main.overview.hide();
    const extension = Main.extensionManager.lookup('luna-desktop@wuild');
    for (let i = 0; i < 30 && extension?.state !== 1; i++) await Scripting.sleep(100);
    assert(extension?.state === 1, `Extension enabled: ${extension?.error}`);
    const controller = extension.stateObj.snapping;
    assert(controller, 'Tiling enabled');
    const nativeFile = Gio.File.new_for_path(`${extension.path}/native/LunaTiling-1.0.typelib`);
    assert(!nativeFile.query_exists(null) || controller.nativeBridge, 'Packaged native helper loaded');
    extension.stateObj.settings.set_boolean('desktop-snap-square-corners', false);
    extension.stateObj.settings.set_int('desktop-snap-gap', 0);
    const launcher = new Gio.SubprocessLauncher({flags: Gio.SubprocessFlags.NONE});
    launcher.set_environ(global.create_app_launch_context(0, -1).get_environment());
    launcher.setenv('GDK_BACKEND', 'wayland', true);
    const process = launcher.spawnv(['gjs', '-m', `${GLib.getenv('LUNA_TEST_ROOT')}/tests/snap-windows.js`]);
    try {
        let windows = [];
        for (let i = 0; i < 30; i++) {
            windows = global.get_window_actors().map(a => a.meta_window).filter(w => w.get_title()?.startsWith('Snap test'));
            if (windows.length === 3) break;
            await Scripting.sleep(150);
        }
        assert(windows.length === 3, 'Three test windows');
        Main.overview.hide();
        await Scripting.sleep(800);
        controller.snap(windows[0], 0, 0, 0);
        await Scripting.sleep(350);
        assert(controller.picker, 'Assist picker visible');
        const firstPicker = controller.picker;
        assert(firstPicker.get_style().includes('rgba(0,0,0,0.68)'), 'Assist backdrop separates cards from underlying windows');
        assert(controller.pickerCards.length === 2, 'Masonry cards for available windows');
        assert(controller.pickerCards[0].get_child().get_first_child() instanceof St.BoxLayout, 'Recommendations use shared icon and title header');
        if (GLib.getenv('LUNA_CAPTURE_SWITCHER')) {
            const stream = Gio.File.new_for_path('/tmp/luna-recommendations-preview.png').replace(null, false, Gio.FileCreateFlags.NONE, null);
            await new Shell.Screenshot().screenshot(false, stream);
            stream.close(null);
        }
        const scroll = firstPicker.get_first_child();
        const content = scroll.get_child();
        assert(Math.abs(scroll.x * 2 + scroll.width - firstPicker.width) <= 2, 'Recommendation grid centered horizontally');
        assert(Math.abs(scroll.y * 2 + scroll.height - firstPicker.height) <= 2, 'Recommendation grid centered vertically');
        assert(Math.abs(scroll.height - content.get_preferred_height(scroll.width)[1]) <= 2, 'Centering uses actual content height');
        const pointer = Clutter.get_default_backend().get_default_seat().create_virtual_device(Clutter.InputDeviceType.POINTER_DEVICE);
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), firstPicker.x + 8, firstPicker.y + 8);
        await Scripting.sleep(100);
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.PRESSED);
        await Scripting.sleep(30);
        assert(!controller.picker && !controller.pickerModal, 'Blank space dismisses recommendations and releases input');
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.RELEASED);
        if (St.Settings.get().enable_animations) {
            assert(controller.retiringActors.has(firstPicker), 'Picker fades out after dismissal');
            assert(!firstPicker.reactive, 'Fading picker does not block clicks');
            await Scripting.sleep(250);
            assert(!controller.retiringActors.has(firstPicker), 'Dismissed picker is cleaned up after animation');
        }
        const group = [...controller.groups][0];
        controller.offer(group);
        await Scripting.sleep(250);
        const occupied = windows[0].get_frame_rect();
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), occupied.x + 80, occupied.y + 80);
        await Scripting.sleep(100);
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.PRESSED);
        await Scripting.sleep(30);
        assert(!controller.picker && !controller.pickerModal, 'Click outside recommendations dismisses modal');
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.RELEASED);
        controller.snap(windows[1], 0, 0, 1);
        controller.clear('picker');
        await Scripting.sleep(350);
        assert(group.windows.size === 2 && group.dividers.length === 1, 'Separately snapped windows share one grid');
        const area = controller.area(0);
        const first = windows[0].get_frame_rect(), second = windows[1].get_frame_rect();
        assert(Math.abs(first.width - area.width / 2) <= 2, `Half width ${first.width}`);
        assert(Math.abs(first.x + first.width - second.x) <= 2, 'Adjacent frames');
        // Initialize the virtual device away from the overview hot corner.
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + area.width / 2, area.y + 100);
        await Scripting.sleep(300);
        Main.overview.hide();
        windows[0].activate(global.get_current_time());
        await Scripting.sleep(500);
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + area.width / 2, area.y + 100);
        await Scripting.sleep(100);
        assert(group.dividers[0].visible, 'Focused group divider is visible');
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.PRESSED);
        await Scripting.sleep(100);
        assert(controller.dividerDrag, 'Real pointer press starts divider drag');
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + area.width * .6, area.y + 100);
        await Scripting.sleep(150);
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.RELEASED);
        await Scripting.sleep(350);
        assert(!controller.dividerDrag && !controller.dividerGrab, 'Real pointer release ends divider drag');
        assert(Math.abs(windows[0].get_frame_rect().width - area.width * .6) <= 2, 'Linked resize');
        assert(Math.abs(windows[1].get_frame_rect().x - (area.x + area.width * .6)) <= 2, 'Real divider drag resizes neighboring window');
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + 100, area.y + 100);
        await Scripting.sleep(100);
        assert(group.dividers[0].get_style().includes('transparent') || group.dividers[0].get_style().includes(',0)'), 'Divider transparent away from pointer');
        controller.begin(windows[0], Meta.GrabOp.RESIZING_E);
        windows[0].move_resize_frame(true, area.x, area.y, Math.round(area.width * .55), area.height);
        await Scripting.sleep(250);
        controller.end();
        await Scripting.sleep(250);
        assert(controller.groups.has(group), 'Native edge resize preserves grid membership');
        assert(Math.abs(windows[1].get_frame_rect().x - (area.x + area.width * .55)) <= 2, 'Native edge resize moves neighboring window');
        extension.stateObj.settings.set_int('desktop-snap-gap', 13);
        await Scripting.sleep(500);
        assert(controller.groups.has(group), 'Spacing change preserves grid');
        assert(windows[1].get_frame_rect().x - windows[0].get_frame_rect().x - windows[0].get_frame_rect().width === 13, 'Odd window spacing applied exactly');
        controller.begin(windows[0], Meta.GrabOp.RESIZING_E);
        windows[0].move_resize_frame(true, area.x + 13, area.y + 13, Math.round(area.width * .6) - 20, area.height - 26);
        await Scripting.sleep(250);
        controller.end();
        await Scripting.sleep(250);
        assert(controller.groups.has(group), 'Resize with spacing keeps the grid');
        assert(windows[1].get_frame_rect().x - windows[0].get_frame_rect().x - windows[0].get_frame_rect().width === 13, 'Resize preserves exact spacing');
        extension.stateObj.settings.set_int('desktop-snap-gap', 0);
        await Scripting.sleep(300);
        extension.stateObj.settings.set_int('desktop-switcher-width-percent', 60);
        const switcher = controller.switcher;
        assert(switcher, 'Luna switcher enabled');
        const entries = switcher.entries();
        assert(entries.filter(entry => entry.group === group).length === 1, 'One entry for the snap group');
        assert(windows.every(w => entries.some(entry => entry.window === w)), 'Individual windows remain available');
        windows[0].minimize(); windows[1].minimize();
        windows[2].activate(global.get_current_time());
        const keyboardSettings = new Gio.Settings({schema_id: 'org.gnome.desktop.wm.keybindings'});
        keyboardSettings.set_strv('switch-windows', ['<Alt>Tab']);
        keyboardSettings.set_strv('switch-applications', ['<Super>Tab']);
        const keyboard = Clutter.get_default_backend().get_default_seat().create_virtual_device(Clutter.InputDeviceType.KEYBOARD_DEVICE);
        await Scripting.sleep(150);
        keyboard.notify_keyval(GLib.get_monotonic_time(), Clutter.KEY_Alt_L, Clutter.KeyState.PRESSED);
        keyboard.notify_keyval(GLib.get_monotonic_time(), Clutter.KEY_Tab, Clutter.KeyState.PRESSED);
        keyboard.notify_keyval(GLib.get_monotonic_time(), Clutter.KEY_Tab, Clutter.KeyState.RELEASED);
        await Scripting.sleep(250);
        assert(switcher.popup, 'Real Alt+Tab opens Luna switcher');
        assert(switcher.popup.panelWidth <= switcher.popup.monitor.width * .6, 'Panel stays within configured monitor width');
        assert(switcher.popup._switcherList.rows.get_n_children() > 1, 'Cards wrap into multiple rows');
        assert(new Set(switcher.popup.layout.widths).size > 1, 'Window proportions produce variable card widths');
        const cardHeights = switcher.popup.buttons.map(button => button.get_child().height);
        assert(Math.max(...cardHeights) - Math.min(...cardHeights) <= 1, 'All cards retain a fixed height');
        assert(switcher.popup.backdrop.width < switcher.popup.monitor.width, 'Backdrop hugs cards instead of spanning monitor');
        const interfaceSettings = new Gio.Settings({schema_id: 'org.gnome.desktop.interface'});
        interfaceSettings.set_string('color-scheme', 'prefer-dark');
        await Scripting.sleep(100);
        assert(switcher.popup.buttons[0].get_child().get_style().includes('42,42,46'), 'Dark style uses dark preview cards');
        assert(switcher.popup.blur.radius === 12 * St.ThemeContext.get_for_stage(global.stage).scale_factor, 'Blur defaults match taskbar panels');
        extension.stateObj.settings.set_int('desktop-switcher-opacity', 35);
        extension.stateObj.settings.set_int('desktop-switcher-blur-radius', 20);
        extension.stateObj.settings.set_int('desktop-switcher-padding', 10);
        extension.stateObj.settings.set_int('desktop-switcher-card-spacing', 8);
        await Scripting.sleep(150);
        assert(switcher.popup.backdrop.get_style().includes(',0.35)'), 'Panel opacity updates live');
        assert(switcher.popup.layout.padding === 20 && switcher.popup.layout.spacing === 8, 'Padding and spacing update layout live');
        extension.stateObj.settings.set_boolean('desktop-switcher-transparency', false);
        assert(!switcher.popup.blur.enabled && switcher.popup.backdrop.get_style().includes(',1)'), 'Opaque mode disables blur');
        extension.stateObj.settings.set_boolean('desktop-switcher-transparency', true);

        const groupIndex = switcher.popup._items.findIndex(entry => entry.group === group);
        assert(groupIndex >= 0, 'Popup includes minimized snap group');
        switcher.popup._select(groupIndex);
        switcher.popup._keyPressHandler(Clutter.KEY_Tab, Meta.KeyBindingAction.SWITCH_WINDOWS_BACKWARD);
        assert(switcher.popup._selectedIndex === (groupIndex + switcher.popup._items.length - 1) % switcher.popup._items.length, 'Backward cycling');
        switcher.popup._keyPressHandler(Clutter.KEY_Tab, Meta.KeyBindingAction.SWITCH_WINDOWS);
        assert(switcher.popup._selectedIndex === groupIndex, 'Forward cycling');
        if (GLib.getenv('LUNA_CAPTURE_SWITCHER')) {
            await Scripting.sleep(200);
            const stream = Gio.File.new_for_path('/tmp/luna-switcher-preview.png').replace(null, false, Gio.FileCreateFlags.NONE, null);
            await new Shell.Screenshot().screenshot(false, stream);
            stream.close(null);
        }
        interfaceSettings.set_string('color-scheme', 'prefer-light');
        await Scripting.sleep(100);
        assert(switcher.popup.buttons[0].get_child().get_style().includes('245,245,245'), 'Light style updates preview cards live');
        keyboard.notify_keyval(GLib.get_monotonic_time(), Clutter.KEY_Alt_L, Clutter.KeyState.RELEASED);
        await Scripting.sleep(350);
        assert(!switcher.popup && !windows[0].minimized && !windows[1].minimized, 'Alt release restores all group members');
        assert(group.windows.size === 2 && controller.groups.has(group), 'Switcher preserves group membership');
        assert(Math.abs(windows[0].get_frame_rect().width - area.width * .6) <= 2, 'Switcher preserves resized group geometry');
        extension.stateObj.settings.set_int('desktop-switcher-width-percent', 40);
        const actualEntries = switcher.entries.bind(switcher);
        switcher.entries = () => [...actualEntries(), ...actualEntries(), ...actualEntries()];
        switcher.open({is_reversed: () => false, get_name: () => 'switch-windows', get_mask: () => 0});
        await Scripting.sleep(200);
        switcher.popup._select(switcher.popup._items.length - 1);
        assert(switcher.popup._switcherList.vadjustment.value > 0, 'Keyboard selection scrolls overflowing rows into view');
        switcher.entries = actualEntries;
        assert(switcher.popup, 'Switcher can reopen');
        extension.stateObj.settings.set_boolean('desktop-snap-switcher-enabled', false);
        assert(!controller.switcher && !switcher.popup, 'Disabling switcher cleans active popup');
        extension.stateObj.settings.set_boolean('desktop-snap-switcher-enabled', true);
        controller.openFlyout();
        assert(controller.bar && controller.modal, 'Keyboard flyout modal');
        controller.event({type: () => Clutter.EventType.KEY_PRESS, get_key_symbol: () => Clutter.KEY_Escape});
        assert(!controller.bar && !controller.modal, 'Escape dismisses modal');
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + 200, area.y + 300);
        await Scripting.sleep(100);
        controller.begin(windows[0], Meta.GrabOp.MOVING);
        assert(controller.barHandle && !controller.bar, 'Window movement shows only a compact tab');
        const handle = controller.barHandle;
        assert(handle.y === Main.layoutManager.monitors[0].y, 'Compact tab is attached to monitor top');
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), handle.x + handle.width / 2, handle.y + 8);
        await Scripting.sleep(300);
        assert(controller.bar && controller.bar._slideContent.translation_y === 0, 'Hover expands layout bar with slide animation');
        assert(handle.width === controller.bar.width && handle.x === controller.bar.x, 'Collapsed and expanded bar share width and alignment');
        assert(handle.get_style().includes(',0.35)'), 'Collapsed bar shares switcher opacity');
        extension.stateObj.settings.set_boolean('desktop-switcher-transparency', false);
        assert(!handle._blur.enabled && handle.get_style().includes(',1)'), 'Collapsed bar follows transparency setting live');
        extension.stateObj.settings.set_boolean('desktop-switcher-transparency', true);
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + 200, area.y + 300);
        await Scripting.sleep(180);
        assert(!controller.bar && controller.barHandle, 'Leaving layouts collapses back to compact tab');
        controller.cancel();
        assert(!controller.barHandle, 'End of drag removes compact tab');
        controller.showBar(0, false);
        assert(controller.barTargets.length === 15, 'Drag bar includes every tile');
        controller.showPreview({x: 10, y: 40, width: 300, height: 400});
        assert(controller.preview, 'Drag preview created');
        interfaceSettings.set_string('accent-color', 'red');
        await Scripting.sleep(100);
        const redGhost = controller.preview.get_style();
        const redTile = controller.barTargets[0].actor.get_style();
        interfaceSettings.set_string('accent-color', 'green');
        await Scripting.sleep(100);
        assert(controller.preview.get_style() !== redGhost, 'Ghost follows live system accent changes');
        assert(controller.barTargets[0].actor.get_style() !== redTile, 'Layout tiles follow system accent changes');
        controller.cancel();
        controller.keyboardSnap('right');
        await Scripting.sleep(250);
        controller.keyboardSnap('down');
        await Scripting.sleep(250);
        const corner = global.display.focus_window.get_frame_rect();
        assert(Math.abs(corner.height - area.height / 2) <= 2, 'Keyboard corner');
        controller.cancel();
        controller.snap(windows[0], 0, 4, 0);
        controller.assign([...controller.groups].find(g => g.windows.has(0) && g.windows.get(0) === windows[0]), 1, windows[1]);
        windows[1].maximize();
        await Scripting.sleep(500);
        assert(![...controller.groups].some(g => [...g.windows.values()].includes(windows[1])), 'Maximize dissolves group');
        controller.snap(windows[1], 0, 0, 1);
        await Scripting.sleep(500);
        assert(Math.abs(windows[1].get_frame_rect().width - area.width / 2) <= 2, `Snap maximized window: ${windows[1].get_frame_rect().width} max=${windows[1].is_maximized()}`);
        if (controller.nativeBridge) {
            controller.reset();
            extension.stateObj.settings.set_boolean('desktop-snap-square-corners', true);
            controller.snap(windows[0], 0, 0, 0);
            controller.snap(windows[1], 0, 0, 1);
            await Scripting.sleep(400);
            const nativeGroup = [...controller.groups].find(g => g.windows.get(0) === windows[0]);
            assert(nativeGroup, 'Native group survives maximized state');
            assert(windows[0].is_maximized() && windows[0].get_frame_rect().width === Math.round(area.width / 2), 'Square styling inside half tile');
            controller.clear('picker');
            windows[0].activate(global.get_current_time());
            await Scripting.sleep(200);
            pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + area.width / 2, area.y + 100);
            await Scripting.sleep(100);
            pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.PRESSED);
            await Scripting.sleep(100);
            assert(controller.dividerDrag, 'Native styled group accepts divider press');
            pointer.notify_absolute_motion(GLib.get_monotonic_time(), area.x + area.width * .6, area.y + 100);
            await Scripting.sleep(150);
            pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.RELEASED);
            await Scripting.sleep(350);
            assert(Math.abs(windows[0].get_frame_rect().width - area.width * .6) <= 2, 'Native constrained window follows grid');
            const originalArea = controller.area.bind(controller);
            controller.area = () => ({x: area.x, y: area.y, width: area.width - 180, height: area.height - 100});
            Main.layoutManager.emit('monitors-changed');
            await Scripting.sleep(500);
            assert(controller.groups.has(nativeGroup), 'Screen resize retains exact group object');
            assert(Math.abs(windows[0].get_frame_rect().width - (area.width - 180) * .6) <= 2, 'Screen resize reflows snapped windows');
            controller.area = originalArea;
            controller.reflow();
            controller.detach(windows[0]);
            await Scripting.sleep(350);
            assert(!windows[0].is_maximized(), 'Unsnap restores normal appearance state');
            assert(controller.groups.has(nativeGroup) && nativeGroup.windows.size === 1, 'Unsnap preserves remaining grid membership');
            controller.reset();
            extension.stateObj.settings.set_boolean('desktop-snap-square-corners', false);
        }
        controller.snap(windows[0], 0, 5, 0);
        await Scripting.sleep(250);
        assert(windows[0].is_maximized(), 'Maximize layout');
        controller.reset();
        assert(controller.groups.size === 0 && !controller.picker && !controller.bar, 'Reset cleans UI');
        controller.snap(windows[0], 0, 0, 0);
        controller.snap(windows[2], 0, 0, 1);
        controller.clear('picker');
        await Scripting.sleep(250);
        controller.switcher.open({is_reversed: () => false, get_name: () => 'switch-windows', get_mask: () => 0});
        await Scripting.sleep(200);
        const closingPopup = controller.switcher.popup;
        const closeIndex = closingPopup._items.findIndex(entry => entry.window === windows[2]);
        closingPopup._select(closeIndex);
        await Scripting.sleep(150);
        const closingCard = closingPopup.buttons[closeIndex];
        const closeButton = closingCard._closeButton;
        assert(closeButton && closeButton.opacity === 0, 'Window close button is hidden before hover');
        const [cardX, cardY] = closingCard.get_transformed_position();
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), cardX + 15, cardY + 15);
        await Scripting.sleep(150);
        assert(closeButton.opacity === 255 && closeButton.reactive, 'Hover reveals close button');
        const [closeX, closeY] = closeButton.get_transformed_position();
        pointer.notify_absolute_motion(GLib.get_monotonic_time(), closeX + closeButton.width / 2, closeY + closeButton.height / 2);
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.PRESSED);
        pointer.notify_button(GLib.get_monotonic_time(), 1, Clutter.ButtonState.RELEASED);
        await Scripting.sleep(350);
        assert(!global.get_window_actors().some(actor => actor.meta_window === windows[2]), 'Close button closes only its window');
        assert(global.get_window_actors().some(actor => actor.meta_window === windows[0]), 'Other windows remain open');
        assert(controller.switcher.popup === closingPopup, 'Closing a window keeps the same switcher open');
        assert(!closingPopup._items.some(entry => entry.window === windows[2]), 'Closed window card is removed');
        assert(!closingPopup._items.some(entry => entry.group), 'Group card disappears when only one member remains');
        closingPopup._keyPressHandler(Clutter.KEY_Tab, Meta.KeyBindingAction.SWITCH_WINDOWS);
        assert(closingPopup._selectedIndex >= 0 && closingPopup._selectedIndex < closingPopup._items.length, 'Keyboard navigation remains valid after closing');
        extension.stateObj.settings.set_boolean('desktop-snap-enabled', false);
        await Scripting.sleep(150);
        assert(!extension.stateObj.snapping, 'Disable via settings');
        extension.stateObj.settings.set_boolean('desktop-snap-enabled', true);
        await Scripting.sleep(150);
        assert(extension.stateObj.snapping, 'Re-enable via settings');
        extension.stateObj.disable();
        print('LUNA_SNAPPING_SHELL_PASS');
    } finally { process.force_exit(); launcher.close(); }
}
